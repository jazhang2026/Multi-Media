def main():
    shots = []
    for scene, speaker, text in UNITS:
        prompt, gen = SCENES[scene]
        shots.append({
            "scene": scene,
            "speaker": speaker,
            "voice": VOICE[speaker],
            "text": text,
            "image": None,
            "prompt": prompt,
            "gen_video": gen,
        })
    for i, s in enumerate(shots, start=1):
        s["id"] = i

    out = BASE / "5" / "shots.json"
